create table if not exists public.warehouses (
  id bigint generated by default as identity primary key,
  name text not null,
  address text not null,
  postcode text,
  country text,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.hauliers (
  id bigint generated by default as identity primary key,
  name text not null,
  service_types text,
  coverage text,
  contact_email text,
  phone text,
  website text,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.quotes (
  id bigint generated by default as identity primary key,
  quote_date date not null,
  haulier_id bigint references public.hauliers(id),
  service_type text not null check (service_type in (
    'UK to UK Pallets',
    'UK to Northern Ireland Pallets',
    'UK to Republic of Ireland Pallets',
    'Full Trailer Load',
    'Port to Door Container'
  )),
  origin text not null,
  destination text not null,
  pallets integer,
  vehicle text,
  container_size text,
  base numeric(12,2) not null default 0,
  fuel numeric(12,2) not null default 0,
  tolls numeric(12,2) not null default 0,
  extras numeric(12,2) not null default 0,
  vat numeric(12,2) not null default 0,
  currency text not null default 'GBP',
  total numeric(12,2) not null,
  valid_until date,
  quote_ref text,
  evidence_url text,
  evidence_note text,
  verification text not null default 'Unverified' check (verification in ('Unverified','Verified','Rejected')),
  verified_by text,
  created_at timestamptz not null default now(),
  constraint verified_quote_has_evidence check (
    verification <> 'Verified' or
    (coalesce(quote_ref,'') <> '' and coalesce(evidence_url,'') <> ''
     and coalesce(evidence_note,'') <> '' and coalesce(verified_by,'') <> '')
  )
);

create index if not exists quotes_route_rank_idx
on public.quotes (service_type, origin, destination, verification, total);
